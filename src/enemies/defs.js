export function eliteStyle(kind, eliteName) {
  const id = (eliteName ?? '').trim().toLowerCase();
  return id === 'thornmother' && kind === SKY_ELITES.thornmother.kind
    ? 'thornmother'
    : id === 'galecaller' && kind === SKY_ELITES.galecaller.kind
      ? 'galecaller'
      : 'hoarder';
}
export function eliteTune(kind, style = 'hoarder') {
  const base = ELITE_TUNE[kind];
  return style === 'hoarder'
    ? base
    : {
        ...base,
        ...SKY_ELITE_TUNE[style],
      };
}
export function eliteDef(kind, style = 'hoarder') {
  const def = ENEMY_DEFS[kind];
  const tune = eliteTune(kind, style);
  return {
    ...def,
    hp: tune.hp,
    radius: def.radius * tune.scale,
    height: def.height * tune.scale,
    walkSpeed: def.walkSpeed * tune.speedMul,
    runSpeed: def.runSpeed * tune.speedMul,
    accel: def.accel * (kind === 'brute' ? 1.6 : 1.2),
    turnRate: def.turnRate * (kind === 'brute' ? 1.1 : 0.9),
    visionRange: def.visionRange + 2,
    hearing: def.hearing + 3,
    noticeTime: def.noticeTime + 0.45,
    knockResist: tune.knockResist,
    poise: tune.poise,
    cooldown: tune.cooldown,
    launchSpeed: tune.launchSpeed,
    size: def.size * tune.scale,
  };
}
